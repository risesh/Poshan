#!/usr/bin/env python3
"""Decode Claude Design "standalone bundle" exports into plain,
greppable HTML files.

The .dc.html export from claude.ai/design is not plain HTML — it's a
self-executing JS bundle: a <script type="__bundler/template"> holds
the actual markup as a JSON-escaped string, using {{ prop }}
placeholders and an inline DCLogic component class. You cannot read
exact spacing/color/copy values by skimming the raw export; you have
to unwrap it first.

Run this after replacing a standalone export with a newer one from
Claude Design (or adding a new one to SOURCES below), so the decoded
copies stay in sync:

    python3 design/decode.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).parent

# (standalone export, decoded output) pairs — add a new pair here for
# every additional Claude Design canvas exported into design/.
SOURCES = [
    (HERE / "Poshan Homepage (standalone).html", HERE / "decoded-source.html"),
    (HERE / "Poshan Legal Pages.html", HERE / "decoded-legal-source.html"),
]

for SRC, OUT in SOURCES:
    content = SRC.read_text(encoding="utf-8")

    match = re.search(
        r'<script type="__bundler/template"[^>]*>(.*?)</script>',
        content,
        re.DOTALL,
    )
    if not match:
        raise SystemExit(f"No __bundler/template script found in {SRC.name} — is this a Claude Design standalone export?")

    template = json.loads(match.group(1).strip())

    header = (
        "<!--\n"
        "  AUTO-GENERATED by design/decode.py from:\n"
        f"  {SRC.name}\n\n"
        "  This is the decoded design canvas — the actual markup/inline-styles\n"
        "  authored in Claude Design, unwrapped from the bundler JS so it can be\n"
        "  grepped directly. Do not hand-edit; re-run design/decode.py instead.\n"
        "  Contains multiple numbered steps/variants (see dv-tname/dv-oid), of\n"
        "  which only a subset may be built into the live site — check CLAUDE.md\n"
        "  for what's implemented vs. reference-only.\n"
        "-->\n"
    )

    OUT.write_text(header + template, encoding="utf-8")
    print(f"Decoded {len(template):,} chars -> {OUT}")
